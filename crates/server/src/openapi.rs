/// What the response of one code is called.
fn response_name(code: &str) -> String {
  code
    .split('-')
    .map(|part| {
      let mut letters = part.chars();
      letters
        .next()
        .map(|first| first.to_uppercase().collect::<String>() + letters.as_str())
        .unwrap_or_default()
    })
    .collect()
}

