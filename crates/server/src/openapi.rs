/// The agency's OpenAPI document.
pub fn openapi() -> Value {
  let mut generator = SchemaSettings::draft2020_12()
    .for_serialize()
    .with(|settings| {
      settings.definitions_path = "/components/schemas".into();
      settings.meta_schema = None;
    })
    .into_generator();

  // The error shape every failure is answered in.
  let _ = generator.subschema_for::<ApiError>();

  let mut tags: Vec<&str> = Vec::new();
  let mut paths: Map<String, Value> = Map::new();
  for operation in OPERATIONS {
    if !tags.contains(&operation.tag) {
      tags.push(operation.tag);
    }
    let parameters: Vec<Value> = operation.params.iter().map(parameter).collect();
    let mut answers: Map<String, Value> = Map::new();
    for &(status, body, stream) in operation.answers {
      let mut content = Map::new();
      if stream {
        content.insert(
          "text/event-stream".into(),
          json!({ "schema": { "$ref": "#/components/schemas/Event" } }),
        );
      }
      if let Some(name) = body {
        let schema = schema(&mut generator, name);
        content.insert("application/json".into(), json!({ "schema": schema }));
      }
      let mut answer = json!({ "description": "Answered." });
      if !content.is_empty() {
        answer["content"] = Value::Object(content);
      }
      answers.insert(status.to_string(), answer);
    }
    let mut codes = vec!["unauthorized"];
    codes.extend(operation.codes.iter().copied());
    for code in &codes {
      let status = status_of(code).to_string();
      answers.entry(status).or_insert_with(|| {
        json!({
          "$ref": format!("#/components/responses/{}", response_name(code)),
        })
      });
    }
    let mut stated = json!({
      "operationId": operation.id,
      "tags": [operation.tag],
      "summary": operation.summary,
      "responses": answers,
      "x-codes": codes,
    });
    if !parameters.is_empty() {
      stated["parameters"] = Value::Array(parameters);
    }
    if let Some(name) = operation.body {
      let schema = schema(&mut generator, name);
      stated["requestBody"] = json!({
        "required": true,
        "content": { "application/json": { "schema": schema } },
      });
    }
    paths.entry(operation.path.to_owned()).or_insert_with(|| json!({}))[operation.method.to_lowercase()] =
      stated;
  }

  let tools: Vec<Value> = TOOLS
    .iter()
    .map(|tool| {
      json!({
        "name": tool.name,
        "description": tool.description,
        "input": schema(&mut generator, tool.input),
        "output": schema(&mut generator, tool.output),
        "route": tool.route,
      })
    })
    .collect();

  let mut responses = Map::new();
  let mut codes: Vec<&str> =
    OPERATIONS.iter().flat_map(|operation| operation.codes.iter().copied()).collect();
  codes.push("unauthorized");
  codes.sort_unstable();
  codes.dedup();
  for code in codes {
    responses.insert(response_name(code), answered(code));
  }

  json!({
    "openapi": "3.1.0",
    "info": {
      "title": "bmo-agency",
      "version": env!("CARGO_PKG_VERSION"),
      "description": DESCRIPTION,
    },
    "servers": [{ "url": "/", "description": "the agency service" }],
    "security": [{ "bearer": [] }],
    "x-layer": "downstream",
    "x-stage": 5,
    "x-calls": CALLS,
    "x-harness": { "plugin": "bmo-agency", "mcp": "bmo-agency mcp", "entry": ENTRY },
    "x-events": EVENTS.as_slice(),
    "tags": tags.iter().map(|tag| json!({ "name": tag })).collect::<Vec<_>>(),
    "paths": paths,
    "components": {
      "schemas": generator.take_definitions(true),
      "responses": responses,
      "securitySchemes": {
        "bearer": {
          "type": "http",
          "scheme": "bearer",
          "description": "The agency's token, from the caller's own configuration; on a route a run calls for itself, the session token the tool host issued the run's program.",
        },
      },
    },
    "x-tools": tools,
    "webhooks": {
      "turn-submitting": {
        "post": {
          "summary": "The turn-submitting hook point, called at the URL registered for it.",
          "requestBody": { "content": { "application/json": { "schema": {} } } },
          "responses": { "200": { "description": "the downstream's answer" } },
        },
      },
    },
    "x-removed": REMOVED.iter().map(|(what, why)| json!({ "what": what, "why": why })).collect::<Vec<_>>(),
    "x-moved-out": MOVED_OUT.iter().map(|(what, to)| json!({ "what": what, "to": to })).collect::<Vec<_>>(),
  })
}

/// The document as the repository keeps it: two-space indented JSON with a closing newline.
pub fn openapi_json() -> String {
  let mut text = serde_json::to_string_pretty(&openapi()).expect("a JSON value always renders");
  text.push('\n');
  text
}

